import 'package:flutter/material.dart';

enum OceanZone {
  sunlight,
  twilight,
  midnight,
  abyss,
  hadal,
}

class DepthZone {
  final OceanZone zone;
  final String name;
  final String alternateName;
  final int minDepth;
  final int maxDepth;
  final String depthRange;
  final String temperature;
  final String pressure;
  final String lightLevel;
  final String description;
  final Color color;
  final Color gradientStart;
  final Color gradientEnd;
  final IconData icon;
  final List<DepthCreature> creatures;
  final List<String> characteristics;

  DepthZone({
    required this.zone,
    required this.name,
    required this.alternateName,
    required this.minDepth,
    required this.maxDepth,
    required this.depthRange,
    required this.temperature,
    required this.pressure,
    required this.lightLevel,
    required this.description,
    required this.color,
    required this.gradientStart,
    required this.gradientEnd,
    required this.icon,
    required this.creatures,
    required this.characteristics,
  });
}

class DepthCreature {
  final String id;
  final String name;
  final String scientificName;
  final String description;
  final String size;
  final String diet;
  final String specialAdaptations;
  final String funFact;
  final IconData icon;
  final Color color;
  final bool isBioluminescent;

  DepthCreature({
    required this.id,
    required this.name,
    required this.scientificName,
    required this.description,
    required this.size,
    required this.diet,
    required this.specialAdaptations,
    required this.funFact,
    required this.icon,
    required this.color,
    this.isBioluminescent = false,
  });
}

